import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'apps/docs/src/data/roadmap.json');
const outputPath = path.join(root, 'ROADMAP.md');
const data = JSON.parse(await readFile(sourcePath, 'utf8'));

function renderRoadmap(roadmap) {
  const lines = [
    '# re;Flux roadmap',
    '',
    `> Generated from \`apps/docs/src/data/roadmap.json\` on ${roadmap.lastUpdated}. Edit the JSON source and run \`npm run sync:roadmap\`; do not edit this file directly.`,
    '',
    '## Product direction',
    '',
    roadmap.overview,
    '',
    '## Product principles',
    '',
  ];
  for (const principle of roadmap.principles) {
    lines.push(`- **${principle.title}:** ${principle.text}`);
  }
  lines.push('', '## Capability status', '');
  for (const feature of roadmap.features) {
    lines.push(`### ${feature.number}. ${feature.title}`, '', `**Status:** ${feature.status}`, '', feature.summary, '', `**Problem:** ${feature.problem}`, '', `**Direction:** ${feature.approach}`, '', '**API example**', '', '```ts', feature.api.trimEnd(), '```', '', '**Acceptance criteria**', '');
    for (const criterion of feature.criteria) lines.push(`- ${criterion}`);
    lines.push('');
  }
  lines.push('## Implementation order', '', `### ${roadmap.implementationHeading}`, '', roadmap.implementationSummary, '');
  for (const [index, step] of roadmap.implementationOrder.entries()) {
    lines.push(`${index + 1}. **${step.title}:** ${step.detail}`);
  }
  lines.push('', '');
  return lines.join('\n');
}

const rendered = renderRoadmap(data);
const mode = process.argv[2] ?? '--check';
if (mode === '--write') {
  await writeFile(outputPath, rendered, 'utf8');
  process.stdout.write('✓ ROADMAP.md generated from the canonical roadmap JSON\n');
} else if (mode === '--check') {
  let current = '';
  try { current = await readFile(outputPath, 'utf8'); } catch { /* report below */ }
  if (current !== rendered) {
    process.stderr.write('ROADMAP.md is out of date. Run `npm run sync:roadmap` and commit the generated file.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('✓ ROADMAP.md matches the canonical roadmap JSON\n');
  }
} else {
  throw new Error(`Unknown mode: ${mode}. Use --write or --check.`);
}
